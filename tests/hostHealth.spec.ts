import { HostHealth } from '../src/common/transfer/hostHealth'
beforeEach(() => { jest.useFakeTimers(); jest.setSystemTime(100000) })
afterEach(() => jest.useRealTimers())
test('three consecutive timeouts open a host for 60s; one half-open probe heals on success', () => {
  const health = new HostHealth()
  for (let i = 0; i < 3; i++) health.observe('https://bad.example', true, true)
  expect(health.canStart('https://bad.example')).toBe(false)
  expect(health.canStart('https://good.example')).toBe(true)
  expect(health.retryAt('https://bad.example')).toBe(160000)
  jest.setSystemTime(160000)
  expect(health.canStart('https://bad.example')).toBe(true)
  expect(health.canStart('https://bad.example')).toBe(false)
  health.observe('https://bad.example', false)
  expect(health.canStart('https://bad.example')).toBe(true)
  expect(jest.getTimerCount()).toBe(0)
})
test('failure EWMA opens a repeatedly failing host and routes prefer healthy alternatives', () => {
  const health = new HostHealth()
  for (let i = 0; i < 4; i++) health.observe('https://bad.example', true)
  expect(health.order(['https://bad.example/a', 'https://good.example/a'])).toEqual(['https://good.example/a', 'https://bad.example/a'])
  expect(health.canStart('https://bad.example')).toBe(false)
})
test('a failed half-open probe reopens the cooldown, and a solitary failure does not ban a host', () => {
  const health = new HostHealth()
  health.observe('https://bad.example', true)
  expect(health.canStart('https://bad.example')).toBe(true)
  for (let i = 0; i < 3; i++) health.observe('https://bad.example', true)
  jest.setSystemTime(160000)
  expect(health.canStart('https://bad.example')).toBe(true)
  health.observe('https://bad.example', true)
  expect(health.retryAt('https://bad.example')).toBe(220000)
})
